/**
 * 报考通道指南内容库（/guide）
 *
 * 内容口径说明：
 *  - 「最新一届」数据均为官方公告原文核实结果，标注了公告发布日期与来源
 *  - 「年度节奏」为历年规律归纳，明确标注为参考，以官方公告为准
 *  - 法规依据均引用文件全称与文号
 *  - 所有数字均来自官方原文，未做估算；官方未披露的留空不补
 */

export type ChannelKey = 'gwy' | 'xuandiao' | 'shiye' | 'rencai'

export interface TimelineItem {
  /** 环节名称 */
  stage: string
  /** 时间表述（已核实的具体日期，或规律性区间） */
  when: string
  /** 补充说明 */
  note?: string
  /** 是否为官方公告核实的确定日期 */
  confirmed?: boolean
}

export interface SubjectItem {
  name: string
  detail: string
}

export interface ChannelGuide {
  key: ChannelKey
  /** 通道全称 */
  title: string
  /** Tab 短标签 */
  tab: string
  /** 主题色（与 lib/theme.ts CATEGORY_COLORS 一致） */
  color: string
  /** 一句话定位 */
  tagline: string
  /** 基本信息 */
  basic: {
    /** 定义 */
    definition: string
    /** 编制与身份 */
    identity: string
    /** 政策依据 */
    legal: string[]
    /** 谁能报 */
    eligibility: string[]
    /** 年龄口径 */
    age: string
  }
  /** 考试信息 */
  exam: {
    /** 组织方式 */
    organizer: string
    /** 笔试科目 */
    subjects: SubjectItem[]
    /** 面试形式 */
    interview: string
    /** 录用程序（官方口径） */
    procedure: string[]
    /** 年度节奏时间线 */
    timeline: TimelineItem[]
  }
  /** 关键区别 / 特别提示 */
  highlights: { title: string; body: string }[]
  /** 最新一届官方核实数据 */
  verified: { label: string; value: string; source: string }[]
}

